source('scripts/comparators/pd_native_input.R')
x<-data.frame(gs_id=c('P2','P1'),gs_NES=c(2,1),gs_adj_pvalue=c(.02,.01))
a<-data.frame(pathway=c('P1','P2'),supplied_original_ES=c(.1,.2))
y<-pd_with_annotations(x,'gs_id',a)
stopifnot(identical(y[names(x)],x),identical(y$supplied_original_ES,c(.2,.1)))
stopifnot(identical(pd_native_selection(x,list(pathway='P1'))[1],'P1'))
for(bad in list(a[1,,drop=FALSE],rbind(a,a[1,]))) {
  failed<-tryCatch({pd_with_annotations(x,'gs_id',bad);FALSE},error=function(e)TRUE);stopifnot(failed)
}
a$gs_NES<-5;stopifnot(inherits(try(pd_with_annotations(x,'gs_id',a),silent=TRUE),'try-error'))
stopifnot(inherits(try(pd_native_selection(x,list(pathway='missing')),silent=TRUE),'try-error'))
cat('PD native input preserves original values and rejects ambiguous joins\n')
source('scripts/comparators/fixture_support.R');comparator_libraries()
f<-list(design=as.formula('~ pmi + age + rin + group'),contrast=c('group','B','A'),
 matched=list(settings=list(conditionA='Control',conditionB='Case',ranking='Wald',effect='apeglm',filterMinCount=10,alpha=.05)))
params<-pd_contrast_params(f)
store<-RNAmel::contrast_store_upsert(list(),'B_vs_A',data.frame(gene='G1',log2FoldChange=1,padj=.01),params=params)
project<-RNAmel::assemble_project('test',contrasts=store)
code<-RNAmel::generate_r_script(project)
stopifnot(grepl('~`pmi` + `age` + `rin` + `group`',code,fixed=TRUE),grepl('c("group", "B", "A")',code,fixed=TRUE),grepl('shrink = TRUE, shrink_type = "apeglm"',code,fixed=TRUE))
cat('RNAmel generated design/contrast/shrink metadata matches the supplied analysis\n')
f$matched$rankedGenes<-c(G2=2,G1=1)
f$nativeAnnotations<-data.frame(supplied_pathway_identifier='P1',supplied_tested_genes='G2;G1',supplied_original_ES=.5,supplied_tested_gene_count=2,supplied_reconstructed_ES=.5,supplied_ES_absolute_difference=0,supplied_ES_tolerance=1e-8)
f$analysisRecord<-list(designFormula='~ pmi + age + rin + group')
e<-pd_rnamel_enrichment(f,data.frame(pathway='P1',NES=2))
stopifnot(identical(e$supplied_ranked_genes$gene,c('G2','G1')),identical(e$supplied_ranked_genes$stat,c(2,1)),identical(e$supplied_tested_membership$P1$testedGenes,c('G2','G1')))
cat('RNAmel settings retain full supplied ordered ranks and membership\n')
